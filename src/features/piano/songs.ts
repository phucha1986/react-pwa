import type { Song, SongNote, SongTitleKey } from './types';

/**
 * All songs share one timing model: notes are stored as (midi, startBeat,
 * durationBeats). Beat -> seconds is derived from the BPM at runtime, so the
 * tempo slider slows songs down without changing pitch or breaking sync.
 *
 * Every song here is traditional / public domain. No copyrighted melodies.
 */

const n = (midi: number, startBeat: number, durationBeats: number): SongNote => ({
  midi,
  startBeat,
  durationBeats,
});

